-- 011_asistente_retirar_intencion_sombra.sql
--
-- Retires `registro_operativo.intencion_sombra`. The shadow domain router that wrote it was
-- removed (change asistente-retirar-enrutador-sombra): nothing writes the column any more, and it
-- never fed any answer. PostgreSQL drops the column's COMMENT and any column-level privilege with
-- it; the whole `asistente` schema is denied to the read-only roles, so no GRANT names it and
-- neither privilege manifest lists it.
--
-- 002 and 003 are published and stay untouched. 002 still declares the column
-- (`CREATE TABLE` and `ADD COLUMN IF NOT EXISTS`), so every convergent run re-adds it and this
-- file drops it right after, in the same ordered pass: the end state is always "no column".
-- The statement is the one ratified DROP of the DDL guard in ArquitecturaAsistenteTests.
ALTER TABLE asistente.registro_operativo DROP COLUMN IF EXISTS intencion_sombra;
